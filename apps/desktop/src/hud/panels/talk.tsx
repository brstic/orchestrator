import { useQuery } from '@tanstack/react-query';
import { useEffect, useMemo, useRef, useState } from 'react';
import type { OrchestratorEvent, SaidFile } from '@orchestrator/contracts';
import { ACTIVITY_LABEL } from '@orchestrator/contracts';
import { Avatar, Badge, Button, Markdown, Window, clock } from '@orchestrator/ui';
import { api } from '../../lib/api.ts';
import { activityOf, currentTaskOf, openQuestionsOf, sessionOfEmployee, useOffice } from '../../lib/store.ts';
import { waitingForLines } from '../../lib/views.ts';
import { QuestionBody, act } from '../core.tsx';
import { registerPanel } from './index.tsx';
import { RepeatChoice, RepeatHint, RoutineList, createRoutine } from './routines.tsx';
import { GivenFile, PendingStrip, SaidFilesOf, usePendingFiles } from './said-files.tsx';
import { FileLinks, Pictures, isPicture } from './task-files.tsx';
import { uploadFile } from './task-files.tsx';

type Line =
  | { kind: 'boss'; id: string; ts: string; text: string; delivery: string; via: string | null; files: SaidFile[] }
  | { kind: 'reply'; id: string; ts: string; text: string }
  /** A file the employee gave: in the conversation itself, or left on a task (`taskId`). */
  | { kind: 'file'; id: string; ts: string; file: SaidFile; caption: string | null; taskId: string | null }
  | { kind: 'note'; id: string; ts: string; text: string; tone: 'good' | 'bad' | 'info' };

/** A file the employee left on a task, shown where they were asked for it: the picture, or the name to download. */
function TaskFileGiven({ taskId, file, caption }: { taskId: string; file: SaidFile; caption: string | null }) {
  const a = useOffice((s) => s.tasks[taskId]?.attachments?.find((x) => x.id === file.id));
  if (!a) return <div className="small muted">{file.name} — no longer on the task</div>;
  return (
    <div className="said-given">
      {isPicture(a) ? <Pictures taskId={taskId} list={[a]} /> : <FileLinks taskId={taskId} list={[a]} />}
      {caption && !isPicture(a) && <div className="small">{caption}</div>}
    </div>
  );
}

const WORKING = new Set(['thinking', 'reading', 'coding', 'testing', 'debugging', 'running_command', 'researching', 'planning', 'reviewing', 'delegating']);

/**
 * Talking to an employee at their desk.
 *
 * What you type is delivered into their real Claude Code session; what comes
 * back is the final message of that turn as Claude Code reported it. Nothing
 * in this thread is generated by Orchestrator.
 */
function TalkPanel({ arg, onClose }: { arg: string | null; onClose: () => void }) {
  const s = useOffice();
  const e = arg ? s.employees[arg] : undefined;
  const [text, setText] = useState('');
  const [asTask, setAsTask] = useState(false);
  // Say it once, or have the office repeat it every so many minutes (a routine).
  const [repeat, setRepeat] = useState({ on: false, minutes: 5 });
  const [busy, setBusy] = useState(false);
  const bottom = useRef<HTMLDivElement>(null);
  const input = useRef<HTMLTextAreaElement>(null);
  // A pasted screenshot, a dropped or chosen file: they go with the next message.
  const pending = usePendingFiles(arg, (why) => useOffice.getState().toast(why, 'error'));
  const picker = useRef<HTMLInputElement>(null);
  const [over, setOver] = useState(false);
  const history = useQuery({ queryKey: ['talk-events', arg], enabled: !!arg, queryFn: () => api<OrchestratorEvent[]>('GET', `/events?employeeId=${arg}&limit=400`) });

  const lines = useMemo(() => {
    if (!e) return [];
    const out: Line[] = [];
    for (const m of Object.values(s.messages)) {
      if (m.toEmployeeId === e.id && (m.from.kind === 'owner' || m.routineId)) out.push({ kind: 'boss', id: m.id, ts: m.createdAt, text: m.said ?? m.body, delivery: m.delivery.status, via: m.delivery.via, files: m.files ?? [] });
    }
    const seen = new Set<string>();
    for (const ev of [...(history.data ?? []), ...s.events]) {
      if (ev.employeeId !== e.id || seen.has(ev.id)) continue;
      seen.add(ev.id);
      const d = ev.data as Record<string, any>;
      if (ev.type === 'agent.turn_finished' && typeof d.lastMessage === 'string' && d.lastMessage.trim()) out.push({ kind: 'reply', id: ev.id, ts: ev.ts, text: d.lastMessage });
      else if (ev.type === 'agent.file_given' && d.file?.id && d.file?.name) out.push({ kind: 'file', id: ev.id, ts: ev.ts, file: d.file as SaidFile, caption: typeof d.caption === 'string' ? d.caption : null, taskId: typeof d.taskId === 'string' ? d.taskId : null });
      else if (ev.type === 'task.completed') out.push({ kind: 'note', id: ev.id, ts: ev.ts, text: ev.summary, tone: 'good' });
      else if (ev.type === 'task.blocked' || ev.type === 'task.verification_failed') out.push({ kind: 'note', id: ev.id, ts: ev.ts, text: ev.summary, tone: 'bad' });
      else if (ev.type === 'task.started' || ev.type === 'agent.question' || ev.type === 'agent.status_report') out.push({ kind: 'note', id: ev.id, ts: ev.ts, text: ev.summary, tone: 'info' });
    }
    return out.sort((a, b) => (a.ts < b.ts ? -1 : 1)).slice(-120);
  }, [e, s.messages, s.events, history.data]);

  useEffect(() => {
    bottom.current?.scrollIntoView({ block: 'end' });
  }, [lines.length]);
  useEffect(() => {
    setTimeout(() => input.current?.focus(), 30);
  }, [arg]);

  if (!e) return null;
  const session = sessionOfEmployee(s.sessions, e.id);
  const live = !!session && (session.status === 'running' || session.status === 'starting');
  const activity = activityOf(session);
  const project = s.projects[e.projectId ?? ''];
  const task = currentTaskOf(s.tasks, e.id);
  const questions = openQuestionsOf(s.questions, e.id);
  const folder = project?.workspace === 'in_place' ? project.repoPath : (session?.cwd ?? e.workingDir ?? project?.repoPath ?? null);
  const hooks = !session || session.capabilities.hooks;

  const send = async () => {
    const body = text.trim();
    const withFiles = pending.files.length > 0;
    if ((!body && !withFiles) || busy) return;
    if (repeat.on && withFiles) return s.toast('A repeated instruction is words only. Take the files out, or send this once.', 'error');
    if (asTask && !body) return s.toast('A task needs a line that says what to do.', 'error');
    setBusy(true);
    try {
      // Repeated by the office from now on: the first run is now, and the office starts their session for it itself.
      if (repeat.on) {
        if (await createRoutine(e.id, e.name, body, repeat.minutes)) {
          setText('');
          setRepeat({ on: false, minutes: repeat.minutes });
        }
        return;
      }
      // Talking to someone who is not at their desk yet brings them in.
      if (!live && e.hostId) await api('POST', `/employees/${e.id}/start`, {});
      if (asTask && e.projectId) {
        const first = body.split('\n')[0]!;
        const made = await api<{ id: string }>('POST', '/tasks', { projectId: e.projectId, title: first.length > 90 ? `${first.slice(0, 87)}…` : first, description: body, assigneeId: e.id });
        // On a task the files are the task's: kept with it, and handed over with it.
        for (const f of pending.files) await uploadFile(made.id, f.file);
        s.toast(`Task created for ${e.name}; it is handed over as soon as they are between turns.`, 'success');
      } else {
        const fileIds = withFiles ? await pending.ready() : [];
        const sent = await api<{ id?: string }>('POST', `/employees/${e.id}/message`, { body, fileIds });
        // I am waiting for what they say back: their answer is announced if I have walked away by then.
        s.asked(e.id, sent?.id ?? null);
      }
      setText('');
      pending.clear();
    } catch (err) {
      s.toast((err as Error).message, 'error');
    } finally {
      setBusy(false);
    }
  };

  const docCount = s.docs[e.id]?.files.length ?? 0;
  return (
    <Window
      kit
      title={
        <span className="row">
          <Avatar appearance={e.appearance} size={30} offline={!live} />
          <span>
            {e.name} <span className="muted" style={{ fontWeight: 500 }}>· {e.title}</span>
          </span>
        </span>
      }
      subtitle={folder ? <span className="mono">{folder}</span> : 'No folder yet — give them a project or a working directory in their profile.'}
      onClose={onClose}
      width={760}
      flush
      actions={
        <>
          <Badge tone={questions.length ? 'warn' : activity === 'blocked' ? 'bad' : live ? 'info' : 'muted'}>{ACTIVITY_LABEL[activity] ?? activity}</Badge>
          {docCount > 0 && (
            <Button small onClick={() => s.openPanel('docs', e.id)} title="The Markdown files in their folder">
              Documents ({docCount})
            </Button>
          )}
          <Button small onClick={() => s.enterWorkstation(e.id)} disabled={!session}>
            Open terminal
          </Button>
        </>
      }
    >
      <RoutineList employeeId={e.id} />
      <div className="talk-thread">
        {lines.length === 0 && (
          <div className="empty">
            <strong>Say what you need.</strong>
            <p>
              {e.name} works in {folder ? 'the folder above' : 'their folder'}. Your words go into their real Claude Code session; their answer appears here when the turn ends.
            </p>
          </div>
        )}
        {lines.map((l) =>
          l.kind === 'boss' ? (
            <div key={l.id} className="talk-row talk-row-me">
              <div className="talk-bubble talk-me">
                <SaidFilesOf employeeId={e.id} files={l.files} />
                <div className="pre">{l.text}</div>
                <div className="talk-meta">
                  {clock(l.ts)} ·{' '}
                  <span title={l.delivery === 'confirmed' ? 'Claude Code acknowledged receiving it' : l.delivery === 'sent' ? 'Typed into the terminal; not acknowledged (yet)' : l.delivery === 'queued' ? 'Waiting until the session is between turns' : 'Could not be delivered'}>
                    {l.delivery === 'confirmed' ? '✓ received' : l.delivery === 'sent' ? 'sent' : l.delivery === 'queued' ? 'waiting for a free moment…' : l.delivery}
                  </span>
                </div>
              </div>
            </div>
          ) : l.kind === 'file' ? (
            <div key={l.id} className="talk-row" data-talk-file={l.file.name}>
              <Avatar appearance={e.appearance} size={26} />
              <div className="talk-bubble talk-them">
                {l.taskId ? <TaskFileGiven taskId={l.taskId} file={l.file} caption={l.caption} /> : <GivenFile employeeId={e.id} file={l.file} caption={l.caption} onError={(why) => s.toast(why, 'error')} />}
                <div className="talk-meta">
                  {clock(l.ts)} · {l.taskId && s.tasks[l.taskId] ? `left on ${s.tasks[l.taskId]!.key}` : 'a file from them'}
                </div>
              </div>
            </div>
          ) : l.kind === 'reply' ? (
            <div key={l.id} className="talk-row">
              <Avatar appearance={e.appearance} size={26} />
              <div className="talk-bubble talk-them">
                <Markdown text={l.text} />
                <div className="talk-meta">{clock(l.ts)} · from their session</div>
              </div>
            </div>
          ) : (
            <div key={l.id} className={`talk-note talk-note-${l.tone}`}>
              {clock(l.ts)} — {l.text}
            </div>
          ),
        )}
        {questions.map((q) => (
          <div key={q.id} className="card" style={{ margin: '4px 0' }}>
            <QuestionBody q={q} />
          </div>
        ))}
        {waitingForLines(s, e.id).map((line) => (
          <div key={line} className="talk-note talk-note-info">{line}</div>
        ))}
        {live && WORKING.has(activity) && (
          <div className="talk-row">
            <Avatar appearance={e.appearance} size={26} />
            <div className="talk-bubble talk-them talk-working">
              {(ACTIVITY_LABEL[activity] ?? activity).toLowerCase()}
              {session?.activityDetail ? <span className="mono"> — {session.activityDetail}</span> : null}
              <span className="talk-dots" />
            </div>
          </div>
        )}
        {!hooks && live && <div className="talk-note talk-note-info">This session has no hooks, so replies cannot be captured here — open the terminal to read them.</div>}
        <div ref={bottom} />
      </div>
      <div
        className={`talk-compose ${over ? 'talk-compose-over' : ''}`}
        onDragOver={(ev) => {
          if (![...ev.dataTransfer.types].includes('Files')) return;
          ev.preventDefault();
          if (!over) setOver(true);
        }}
        onDragLeave={(ev) => !ev.currentTarget.contains(ev.relatedTarget as Node | null) && setOver(false)}
        onDrop={(ev) => (setOver(false), pending.onDrop(ev))}
      >
        <PendingStrip files={pending.files} onRemove={pending.remove} />
        <textarea
          ref={input}
          value={text}
          rows={2}
          placeholder={live ? `Tell ${e.name} what to do… (paste a screenshot with Ctrl+V)` : `${e.name} is not at their desk. Sending a message starts their session.`}
          onChange={(ev) => setText(ev.target.value)}
          onPaste={pending.onPaste}
          onKeyDown={(ev) => {
            if (ev.key === 'Enter' && !ev.shiftKey) {
              ev.preventDefault();
              void send();
            }
          }}
        />
        <div className="row spread">
          <label className="check small" title={e.projectId ? 'A task is tracked on the board and only counts as done after Orchestrator verifies it' : 'Needs a project or folder'}>
            <input type="checkbox" checked={asTask && !repeat.on} disabled={!e.projectId || repeat.on} onChange={(ev) => setAsTask(ev.target.checked)} />
            Track as a task{task ? ` (after ${task.key})` : ''} — verified when done
          </label>
          <RepeatChoice on={repeat.on} minutes={repeat.minutes} name={e.name} onChange={(on, minutes) => setRepeat({ on, minutes })} />
          <div className="row">
            <input ref={picker} type="file" multiple hidden onChange={(ev) => (pending.add([...(ev.target.files ?? [])]), (ev.target.value = ''))} />
            <Button small onClick={() => picker.current?.click()} title="A picture or a document that goes with what you say. A screenshot can simply be pasted (Ctrl+V), and files dropped here.">
              Attach…
            </Button>
            <span className="small faint">Enter to send · Shift+Enter for a new line</span>
            {session && live && (
              <Button small onClick={() => act(() => api('POST', `/employees/${e.id}/pause`, {}), `${e.name} paused`)} title="Stops what they are doing right now. They do nothing more until you resume them.">
                Pause {e.name}
              </Button>
            )}
            <Button variant="primary" small disabled={(!text.trim() && !pending.files.length) || busy || (!live && !e.hostId)} onClick={send}>
              {repeat.on ? 'Repeat' : asTask ? 'Assign' : 'Send'}
            </Button>
          </div>
        </div>
        {repeat.on && <RepeatHint name={e.name} />}
      </div>
    </Window>
  );
}

registerPanel('talk', TalkPanel);
